-- Client Isolation Policies
CREATE POLICY "client_isolation_products" ON public.products
  USING (client_id = COALESCE(current_setting('app.current_client_id', true), client_id));

CREATE POLICY "client_isolation_orders" ON public.orders
  USING (client_id = COALESCE(current_setting('app.current_client_id', true), client_id));

CREATE POLICY "client_isolation_attendance" ON public.attendance
  USING (client_id = COALESCE(current_setting('app.current_client_id', true), client_id));

