-- =========================================================
-- OFFICE TO THE TOP - SUPABASE POSTGRES SCHEMA
-- Multi-Agent WhatsApp & Client UMKM Management Architecture
-- =========================================================

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. TODOS (Supabase Quickstart / Verification Table)
CREATE TABLE IF NOT EXISTS public.todos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    is_complete BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. AGENTS REGISTRY
CREATE TABLE IF NOT EXISTS public.agents (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    role TEXT,
    emoji TEXT,
    color TEXT,
    triggers JSONB DEFAULT '[]'::jsonb,
    priority INTEGER DEFAULT 10,
    enabled BOOLEAN DEFAULT TRUE,
    desk JSONB DEFAULT '{"x":0,"z":0}'::jsonb,
    config JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 3. TASKS QUEUE
CREATE TABLE IF NOT EXISTS public.tasks (
    id TEXT PRIMARY KEY,
    agent_id TEXT REFERENCES public.agents(id) ON DELETE CASCADE,
    chat_id TEXT NOT NULL,
    sender TEXT,
    push_name TEXT,
    text TEXT,
    message_id TEXT,
    message_type TEXT,
    media_base64 TEXT,
    mime_type TEXT,
    is_group INTEGER DEFAULT 0,
    instance TEXT,
    status TEXT DEFAULT 'pending', -- pending, working, done, failed
    result JSONB,
    error TEXT,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_tasks_agent_status ON public.tasks(agent_id, status);
CREATE INDEX IF NOT EXISTS idx_tasks_chat ON public.tasks(chat_id);

-- 4. AGENT EVENTS (Realtime Dashboard)
CREATE TABLE IF NOT EXISTS public.agent_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id TEXT REFERENCES public.agents(id) ON DELETE CASCADE,
    event TEXT NOT NULL, -- working, idle, error, log
    message TEXT,
    metadata JSONB,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_agent_events_agent_time ON public.agent_events(agent_id, created_at DESC);

-- 5. AGENT MEMORY (KV store per agent)
CREATE TABLE IF NOT EXISTS public.agent_memory (
    agent_id TEXT REFERENCES public.agents(id) ON DELETE CASCADE,
    key TEXT NOT NULL,
    value JSONB,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    PRIMARY KEY (agent_id, key)
);

-- 6. PROCESSED MESSAGES (Webhook Deduplication)
CREATE TABLE IF NOT EXISTS public.processed_messages (
    message_id TEXT PRIMARY KEY,
    chat_id TEXT,
    processed_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_processed_messages_time ON public.processed_messages(processed_at);

-- 7. WA ALLOWED CHATS (Access Control List)
CREATE TABLE IF NOT EXISTS public.wa_allowed_chats (
    jid TEXT PRIMARY KEY,
    description TEXT,
    added_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 8. CLIENTS REGISTRY (Multi-tenant UMKM Clients)
CREATE TABLE IF NOT EXISTS public.clients (
    id TEXT PRIMARY KEY, -- slug e.g. warung-makmur
    name TEXT NOT NULL,
    package TEXT NOT NULL, -- Bronze, Silver, Gold, Platinum
    wa_number TEXT,
    status TEXT DEFAULT 'active', -- active, trial, suspended
    config JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 9. UMKM DOMAIN TABLES (Products, Orders, Attendance)
CREATE TABLE IF NOT EXISTS public.products (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    client_id TEXT NOT NULL,
    name TEXT NOT NULL,
    price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    stock INTEGER NOT NULL DEFAULT 0,
    category TEXT,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_products_client ON public.products(client_id);

CREATE TABLE IF NOT EXISTS public.orders (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    client_id TEXT NOT NULL,
    customer_name TEXT,
    customer_phone TEXT,
    items JSONB DEFAULT '[]'::jsonb,
    total_price NUMERIC(12, 2) DEFAULT 0,
    status TEXT DEFAULT 'pending', -- pending, paid, processing, completed, cancelled
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_orders_client ON public.orders(client_id);

CREATE TABLE IF NOT EXISTS public.attendance (
    id UUID DEFAULT uuid_generate_v4() PRIMARY KEY,
    client_id TEXT NOT NULL,
    employee_name TEXT NOT NULL,
    check_in TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()),
    check_out TIMESTAMPTZ,
    selfie_url TEXT,
    status TEXT DEFAULT 'present',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_attendance_client ON public.attendance(client_id);

-- =========================================================
-- RLS POLICIES & FUNCTIONS
-- =========================================================

-- Session context function for client isolation
CREATE OR REPLACE FUNCTION set_client_context(p_client_id text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM set_config('app.current_client_id', p_client_id, true);
END; $$;

